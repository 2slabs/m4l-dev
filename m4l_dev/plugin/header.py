"""A plugin's generated C++ header: its host parameters and how each reaches the device's parts (parameters.py), its
Stored Only values, its presets, its latency and its gen~ programs' specs, for the kit's C++ (plugin/cpp/). Written
by a device's plugin/generate.py; read by the plugin's C++ and nowhere else."""
import json

from m4l_dev.genexpr import c_double_literal

NOTICE = "// Generated by plugin/generate.py from the device's sources. Don't edit: run python3 plugin/generate.py.\n"
ROUTE_KINDS = {"gen": "RouteKind::Gen", "message": "RouteKind::Message", "raw": "RouteKind::Raw"}


def c_string(text):
    return json.dumps(text, ensure_ascii=False)


def c_doubles(name, values):
    return f"inline constexpr double {name}[] = {{" + ", ".join(c_double_literal(v) for v in values) + "};"


def identifier(text):
    return "".join(c if c.isalnum() else "_" for c in text)


def plugin_header(namespace, destinations, parameters, stored, presets, latency_samples, programs):
    """The header's text. `destinations`: the destination names in order (Route::destination indexes them);
    `programs`: [(name, C prefix)] for each exported gen~ program, each becoming a `twosl::plugin::ProgramSpec`."""
    lines = [NOTICE, "#pragma once", "", '#include "PluginTable.h"', ""]
    lines += [f'#include "{prefix}.h"' for _, prefix in programs]
    lines += ["", f"namespace {namespace}", "{", "using namespace twosl::plugin;", "",
              "// where the device's patch sends parameters, by Route::destination",
              "enum Destination", "{"]
    lines += [f"    {identifier(name)}Destination = {i}," for i, name in enumerate(destinations)]
    lines += ["};", ""]

    def routes_block(owner, routes):
        out = []
        for i, route in enumerate(routes):
            base = f"{identifier(owner)}_route{i}"
            if "choices" in route:
                out.append(c_doubles(f"{base}_choices", route["choices"]))
            if "beats" in route:
                out.append(c_doubles(f"{base}_beats", route["beats"]))
        entries = []
        for i, route in enumerate(routes):
            base = f"{identifier(owner)}_route{i}"
            entries.append(
                f"    {{ {identifier(route['to'])}Destination, {ROUTE_KINDS[route['kind']]}, {route['target']}, "
                f"{c_string(route['message']) if route['message'] else 'nullptr'}, "
                f"{c_double_literal(route.get('scale', 0.0))}, {c_double_literal(route.get('offset', 0.0))}, "
                f"{base + '_choices' if 'choices' in route else 'nullptr'}, "
                f"{base + '_beats' if 'beats' in route else 'nullptr'} }},")
        if entries:
            out.append(f"inline constexpr Route {identifier(owner)}_routes[] = {{")
            out += entries
            out.append("};")
        return out

    for p in parameters + stored:
        lines += routes_block(p["id"], p["routes"])
        if p.get("items"):
            lines.append(f"inline constexpr const char* {identifier(p['id'])}_items[] = {{"
                         + ", ".join(c_string(item) for item in p["items"]) + "};")
    lines += ["", f"inline constexpr int parameterCount = {len(parameters)};",
              "inline constexpr Parameter parameters[parameterCount] = {"]
    for p in parameters:
        routes = f"{identifier(p['id'])}_routes" if p["routes"] else "nullptr"
        items = f"{identifier(p['id'])}_items" if p["items"] else "nullptr"
        unit = -1 if p["unit_style"] is None else p["unit_style"]
        lines.append(f"    {{ {c_string(p['id'])}, {c_string(p['name'])}, Kind::{p['kind']}, "
                     f"{c_double_literal(p['minimum'])}, {c_double_literal(p['maximum'])}, "
                     f"{c_double_literal(p['exponent'])}, {c_double_literal(p['initial'])}, {unit}, "
                     f"{len(p['items'])}, {items}, {len(p['routes'])}, {routes} }},")
    lines += ["};", ""]
    lines.append(f"inline constexpr int storedCount = {len(stored)};")
    if stored:
        lines.append("inline constexpr Stored stored[storedCount] = {")
        for s in stored:
            routes = f"{identifier(s['id'])}_routes" if s["routes"] else "nullptr"
            lines.append(f"    {{ {c_string(s['id'])}, {c_string(s['name'])}, {c_double_literal(s['initial'])}, "
                         f"{len(s['routes'])}, {routes} }},")
        lines.append("};")
    else:
        lines.append("inline constexpr const Stored* stored = nullptr;")
    lines += ["", "// the parameters the plugin handles itself (no route): by id"]
    for i, p in enumerate(parameters):
        if not p["routes"]:
            lines.append(f"inline constexpr int {identifier(p['id'])}Parameter = {i};")
    lines += ["", "// how late the output is, in whole samples: the device's Defined Latency, reported to the host",
              f"inline constexpr int latencySamples = {latency_samples};", ""]
    for name, prefix in programs:
        upper = prefix.upper()
        lines += [f"// the {name} gen~ program (generated/{prefix}.c)",
                  f"inline constexpr ProgramSpec {identifier(name)}Program {{ {prefix}_render, {prefix}_noise_seed, "
                  f"{upper}_INPUTS, {upper}_OUTPUTS, {upper}_PARAMS, {prefix}_param_names, {prefix}_param_defaults, "
                  f"{prefix}_param_lowest, {prefix}_param_highest, {upper}_HISTORIES, {prefix}_history_names, "
                  f"{prefix}_history_initials, {upper}_DELAY_MEMORY, {upper}_DELAYS }};"]
    lines += ["", "// the factory presets: each parameter's value as Live holds it (a choice's index), then each Stored "
              "value"]
    for i, (title, held, kept) in enumerate(presets):
        lines.append(c_doubles(f"preset{i}_values", held))
        if stored:
            lines.append(c_doubles(f"preset{i}_stored", kept))
    lines += [f"inline constexpr int presetCount = {len(presets)};", "inline constexpr Preset presets[presetCount] = {"]
    for i, (title, held, kept) in enumerate(presets):
        lines.append(f"    {{ {c_string(title)}, preset{i}_values, {f'preset{i}_stored' if stored else 'nullptr'} }},")
    lines += ["};", f"}} // namespace {namespace}", ""]
    return "\n".join(lines)
