import sys, json
src, out = sys.argv[1], sys.argv[2]
want = set(range(32, 127)) | {0x266F, 0x266D, 0x221E, 0xB7, 0x2013, 0x2014, 0x2192, 0x2190, 0x25B8, 0x2022, 0x21BB, 0x25CF, 0x25CB, 0x00D7, 0x2026, 0x221A}
glyphs = {}
cur = None
with open(src, encoding="latin-1") as f:
    for line in f:
        parts = line.split()
        if not parts: continue
        k = parts[0]
        if k == "STARTCHAR": cur = {"rows": []}
        elif k == "ENCODING": cur["cp"] = int(parts[1])
        elif k == "DWIDTH": cur["dw"] = int(parts[1])
        elif k == "BBX": cur["bbx"] = [int(x) for x in parts[1:5]]
        elif k == "BITMAP": cur["in"] = True
        elif k == "ENDCHAR":
            if cur.get("cp") in want:
                w, h, xo, yo = cur["bbx"]
                glyphs[cur["cp"]] = [cur["dw"], w, h, xo, yo] + [int(r, 16) for r in cur["rows"]]
            cur = None
        elif cur is not None and cur.get("in"):
            cur["rows"].append(parts[0])
missing = sorted(want - set(glyphs))
js = ("// Cozette (MIT, (c) 2020-2025 Ines / slavfox), 13 px, as bitmaps: codepoint -> [advance, w, h, xoff, yoff, rows...].\n"
      "// Rows are bit masks, most significant bit = leftmost pixel of a byte-padded row. Generated by bdf2js.py from cozette.bdf v1.30.0.\n"
      "var COZETTE = " + json.dumps({str(k): v for k, v in sorted(glyphs.items())}, separators=(",", ":")) + ";\n")
if missing:
    # a missing glyph would draw as "?" on the device: refuse to write a font that lacks one
    sys.exit(f"bdf2js.py: {src} has no glyph for {len(missing)} wanted codepoint(s): "
             + ", ".join(f"U+{m:04X} {chr(m)!r}" for m in missing) + f"; {out} not written")
open(out, "w").write(js)
print(len(glyphs), "glyphs, none missing;", "bytes:", len(js))
